/// Phase 1 of the typed client: ids, read models, `ZonaiTables`, and
/// `get` / `list` / `count` with an `Authorization` on every method.
///
/// Deliberately *not* here, and not because they were forgotten: `ColumnRef`
/// tokens, typed `Where` / `OrderByTerm`, the `Patch` family and the write
/// surface (phase 2); `ExpandPath` chaining and `listen` mirrors (phase 3);
/// enum columns as Dart enums and custom operations (phase 4).
///
/// The output is a value, never a write. `--check` has to be able to compare a
/// generation against disk without performing it, which is only possible while
/// the result is still in hand.
final class DartClientEmitter implements ClientEmitter {
  const DartClientEmitter();

  /// The library a consumer imports. Everything else is reachable from here.
  static const barrelFileName = 'zonai_client.g.dart';

  /// Shared runtime: the parse helpers and [Authorization]. One copy, not one
  /// per table.
  static const runtimeFileName = 'zonai_runtime.g.dart';

  @override
  Map<String, String> emit(ClientGenerationInput input) {
    final tables = input.schema.tables;
    final names = ClientNameTable.forTables(tables.keys, input.settings);

    for (final collision in names.collisions) {
      logger.warn(collision.message);
    }

    return {
      barrelFileName: _barrel(input, names),
      runtimeFileName:
          _header(input, about: 'Shared runtime.') + kClientRuntimeSource,
      for (final entry in tables.entries)
        names[entry.key]!.file: _table(input, entry.value, names),
    };
  }

  /// The header every generated file carries.
  ///
  /// §8.3 is in here rather than only in the docs on purpose: a typed API
  /// *reads* as a guarantee, and the file a developer has open is where that
  /// misreading happens.
  ///
  /// `// dart format off` because this output lands in a repo the *consumer*
  /// owns, where `lib/gen` is not excluded from anything. Reformatting it
  /// would put a project's format gate and `zonai gen client --check` in
  /// permanent disagreement: one demands a change the next generation reverts.
  /// The alternative -- formatting the emitted source with `dart_style` here
  /// -- would make the CLI's dart_style version, not the consumer's SDK, decide
  /// what their committed files look like, so version skew becomes churn.
  String _header(ClientGenerationInput input, {required String about}) {
    return '''
$kGeneratedClientHeader
//
// $about
// Generated by `zonai gen client` (zonai ${input.generatorVersion}).
// Schema: ${input.schema.hash}
//
// Types say nothing about permission. `canView` / `canList` / `canUpdate` are
// evaluated on the server and still reject at runtime -- a method existing
// here means the shape is known, not that this caller may call it.

// ignore_for_file: type=lint
// dart format off

''';
  }

  /// The barrel: exports, and the extension that hangs the tables off
  /// `ZonaiClient`.
  String _barrel(ClientGenerationInput input, ClientNameTable names) {
    final tables = input.schema.tables.keys.toList();
    final buffer = StringBuffer(
      _header(input, about: 'The generated typed client.'),
    );

    buffer
      ..writeln("import 'package:zonai_client/zonai_client.dart';")
      ..writeln();
    for (final table in tables) {
      buffer.writeln("import '${names[table]!.file}';");
    }
    buffer
      ..writeln()
      ..writeln(
        "export '$runtimeFileName' show Authorization, ZonaiRowParseException;",
      );
    for (final table in tables) {
      buffer.writeln("export '${names[table]!.file}';");
    }

    buffer
      ..writeln()
      ..writeln('/// The generated tables, hung off the existing client.')
      ..writeln('///')
      ..writeln('/// An extension, never a fork: the dependency arrow points')
      ..writeln('/// generated -> `zonai_client` and never back, so')
      ..writeln('/// `client.posts.list(...)` and')
      ..writeln("/// `client.db.list(body: ListBody(table: 'posts'), ...)` are")
      ..writeln('/// both valid in one file.')
      ..writeln('extension ZonaiTables on ZonaiClient {');

    for (final table in tables) {
      final name = names[table]!;
      final shape = input.schema.tables[table]!;
      buffer
        ..writeln(
          '  /// The `$table` table${shape.isView ? ', a read-only '
                    'view' : ''}.',
        )
        ..writeln('  ${name.api} get ${name.getter} => ${name.api}(db);');
      if (table != tables.last) buffer.writeln();
    }

    buffer.writeln('}');
    return buffer.toString();
  }

  /// One table: its id type, read model, expanded holder and API.
  String _table(
    ClientGenerationInput input,
    TableSchemaShape shape,
    ClientNameTable names,
  ) {
    final table = shape.table;
    final name = names[table]!;
    final columns = [
      for (final column in shape.columns)
        if (ColumnBinding.forColumn(column, table: table, names: names)
            case final binding?)
          binding,
    ];
    final expands = ExpandBinding.forTable(shape, names: names);
    final secrets = [
      for (final column in shape.columns)
        if (column.isSecret) column.name,
    ];

    final buffer = StringBuffer(
      _header(
        input,
        about: '`$table`${shape.isView ? ' (a read-only view)' : ''}.',
      ),
    );

    buffer.writeln("import 'package:zonai_client/zonai_client.dart';");
    buffer.writeln();
    buffer.writeln("import '../$runtimeFileName';");
    for (final import in _importsFor(shape, names)) {
      buffer.writeln("import '$import';");
    }
    buffer.writeln();

    buffer
      ..writeln("const _r = ZonaiRowReader('$table');")
      ..writeln();

    _writeId(buffer, shape, name);
    _writeRow(buffer, shape, name, columns, expands, secrets);
    if (expands.isNotEmpty) _writeExpanded(buffer, name, expands);
    _writeApi(
      buffer,
      shape,
      name,
      columns,
      _expandExample(expands, input.schema.tables, names),
    );

    return buffer.toString();
  }

  /// The other generated libraries this one names.
  ///
  /// A self-referencing foreign key (`users.manager_id -> users.id`) resolves
  /// to this same file, so it is dropped rather than emitted as an import of
  /// itself.
  List<String> _importsFor(TableSchemaShape shape, ClientNameTable names) {
    final imports = <String>{};
    for (final column in shape.columns) {
      if (column.isSecret) continue;
      if (column.foreignKey case final fk?) {
        if (fk.table == shape.table) continue;
        if (names[fk.table] case final target?) {
          imports.add(target.baseFileName);
        }
      }
    }
    return imports.toList()..sort();
  }

  /// An `expand` example built from THIS table's own foreign keys.
  ///
  /// It used to be the literal `['author_id', 'author_id.company_id']` for
  /// every table in every project -- those are `apps/playground`'s columns, so
  /// the line read as correct there and was wrong everywhere else. It was
  /// printed even on tables with no foreign keys at all, telling a developer
  /// to expand a column their schema does not have.
  ///
  /// Second hop only when the target genuinely has one, because the dotted
  /// form is the whole thing the example exists to teach; a one-element list
  /// demonstrates nothing. Null when the table has no expandable relation --
  /// [_writeList] then says so instead of inventing a column.
  /// Derived from [ExpandBinding.forTable] rather than from the columns
  /// directly, so the example can only ever name a path the generated
  /// `expanded` class actually offers. Reading the foreign keys myself was the
  /// first attempt and it produced `['photo']` for `posts`: `photo` IS a
  /// foreign key, but it points at `_photos`, a skipped system table, so the
  /// generated client cannot expand it. One predicate, in one place.
  String? _expandExample(
    List<ExpandBinding> expands,
    Map<String, TableSchemaShape> tables,
    ClientNameTable names,
  ) {
    if (expands.isEmpty) return null;
    final first = expands.first;

    final second = switch (tables[first.targetTable]) {
      final target? =>
        ExpandBinding.forTable(target, names: names)
            // `a.a` teaches the dotted form less clearly than a hop to a
            // different table.
            .where((next) => next.targetTable != first.targetTable)
            .firstOrNull,
      _ => null,
    };

    if (second == null) return "['${first.wireKey}']";
    return "['${first.wireKey}', '${first.wireKey}.${second.wireKey}']";
  }

  void _writeId(StringBuffer buffer, TableSchemaShape shape, TableNames name) {
    final primaryKey = _primaryKey(shape);
    if (primaryKey == null || primaryKey.kind != ColumnShapeKind.id) return;

    buffer
      ..writeln('/// A `${shape.table}` row id.')
      ..writeln('///')
      ..writeln('/// An extension type over `String`, so it erases at runtime:')
      ..writeln(
        '/// it survives `jsonEncode` and `SendPort.send` untouched and',
      )
      ..writeln('/// needs no custom encoder. Passing a different table\'s id')
      ..writeln('/// where this one belongs stops compiling.')
      ..writeln('extension type const ${name.id}(String value) {')
      ..writeln('  /// Parses an id from a raw JSON value.')
      ..writeln('  static ${name.id} fromJson(Object? json) => switch (json) {')
      ..writeln('        final String value => ${name.id}(value),')
      ..writeln('        _ => throw ZonaiRowParseException(')
      ..writeln("            table: '${shape.table}',")
      ..writeln("            column: '${primaryKey.name}',")
      ..writeln("            expected: 'id (String)',")
      ..writeln('            actual: json.runtimeType,')
      ..writeln('          ),')
      ..writeln('      };')
      ..writeln()
      ..writeln('  String toJson() => value;')
      ..writeln('}')
      ..writeln();
  }

  void _writeRow(
    StringBuffer buffer,
    TableSchemaShape shape,
    TableNames name,
    List<ColumnBinding> columns,
    List<ExpandBinding> expands,
    List<String> secrets,
  ) {
    buffer
      ..writeln('/// One `${shape.table}` row, decoded.')
      ..writeln('///');
    if (secrets.isNotEmpty) {
      buffer
        ..writeln(
          '/// ${secrets.map((s) => '`$s`').join(', ')} '
          '${secrets.length == 1 ? 'is a secret column and is' : 'are secret '
                    'columns and are'} stripped from every',
        )
        ..writeln(
          '/// response, so ${secrets.length == 1 ? 'it has' : 'they '
                    'have'} no field here -- absent rather than',
        )
        ..writeln('/// nullable-and-always-null.')
        ..writeln('///');
    }
    buffer
      ..writeln('/// Values arrive as raw SQLite storage and are decoded here:')
      ..writeln('/// epoch milliseconds become `DateTime`, `0`/`1` becomes')
      ..writeln('/// `bool`, JSON-encoded text becomes a list or a map.')
      ..writeln('final class ${name.row} {')
      ..writeln('  const ${name.row}({');

    for (final column in columns) {
      buffer.writeln(
        '    ${column.isNullable ? '' : 'required '}this.${column.field},',
      );
    }
    if (expands.isNotEmpty) buffer.writeln('    this.expanded,');
    buffer
      ..writeln('  });')
      ..writeln();

    for (final column in columns) {
      buffer.writeln(
        '  /// `${column.wireKey}` -- ${column.column.kind.toJson()}.',
      );
      buffer.writeln('  final ${column.type} ${column.field};');
      buffer.writeln();
    }
    if (expands.isNotEmpty) {
      buffer
        ..writeln('  /// Related rows, when the call asked for them. Null')
        ..writeln('  /// otherwise -- an unexpanded row is not an error.')
        ..writeln('  final ${name.expanded}? expanded;')
        ..writeln();
    }

    buffer.writeln(
      '  factory ${name.row}.fromJson(Map<String, Object?> json) => '
      '${name.row}(',
    );
    for (final column in columns) {
      buffer.writeln('        ${column.field}: ${column.parseExpression},');
    }
    if (expands.isNotEmpty) {
      buffer.writeln(
        "        expanded: ${name.expanded}.tryFromJson(json['expanded']),",
      );
    }
    buffer
      ..writeln('      );')
      ..writeln('}')
      ..writeln();
  }

  void _writeExpanded(
    StringBuffer buffer,
    TableNames name,
    List<ExpandBinding> expands,
  ) {
    buffer
      ..writeln('/// The rows related to a `${name.table}` row.')
      ..writeln('///')
      ..writeln(
        '/// One field per expandable foreign key, keyed on the wire by',
      )
      ..writeln('/// the foreign-key column name. Each related row carries its')
      ..writeln('/// own `expanded`, so depth is recursion rather than a new')
      ..writeln('/// type.')
      ..writeln('final class ${name.expanded} {')
      ..writeln('  const ${name.expanded}({');
    for (final expand in expands) {
      buffer.writeln('    this.${expand.field},');
    }
    buffer
      ..writeln('  });')
      ..writeln();

    for (final expand in expands) {
      buffer
        ..writeln(
          '  /// The `${expand.targetTable}` row `${expand.wireKey}` '
          'points at.',
        )
        ..writeln('  final ${expand.rowType}? ${expand.field};')
        ..writeln();
    }

    buffer.writeln(
      '  factory ${name.expanded}.fromJson(Map<String, Object?> json) => '
      '${name.expanded}(',
    );
    for (final expand in expands) {
      buffer.writeln(
        '        ${expand.field}: switch '
        "(ZonaiRowReader.nested(json['${expand.wireKey}'])) {",
      );
      buffer
        ..writeln('          final row? => ${expand.rowType}.fromJson(row),')
        ..writeln('          _ => null,')
        ..writeln('        },');
    }
    buffer
      ..writeln('      );')
      ..writeln()
      ..writeln('  /// Null when the response carried no `expanded` object.')
      ..writeln(
        '  static ${name.expanded}? tryFromJson(Object? json) => '
        'switch (ZonaiRowReader.nested(json)) {',
      )
      ..writeln('        final map? => ${name.expanded}.fromJson(map),')
      ..writeln('        _ => null,')
      ..writeln('      };')
      ..writeln('}')
      ..writeln();
  }

  void _writeApi(
    StringBuffer buffer,
    TableSchemaShape shape,
    TableNames name,
    List<ColumnBinding> columns,
    String? expandExample,
  ) {
    final primaryKey = _primaryKey(shape);
    final keyed = primaryKey == null
        ? null
        : columns
              .where((binding) => binding.column.name == primaryKey.name)
              .firstOrNull;

    buffer
      ..writeln('/// Reads of the `${shape.table}` table.')
      ..writeln('///');
    if (shape.isView) {
      buffer
        ..writeln('/// A read-only view: it has no `sqlite_master` row and no')
        ..writeln('/// write operations, so there is nothing else to offer.')
        ..writeln('///');
    }
    buffer
      ..writeln('/// Every method takes an optional `as` and falls through to')
      ..writeln('/// the client\'s ambient token when it is omitted.')
      ..writeln('final class ${name.api} {')
      ..writeln('  const ${name.api}(this._db);')
      ..writeln()
      ..writeln('  /// The wire name of this table.')
      ..writeln("  static const table = '${shape.table}';")
      ..writeln()
      ..writeln('  final Db _db;')
      ..writeln();

    _writeGet(buffer, name, keyed);
    _writeList(buffer, name, expandExample);
    _writeCount(buffer, name);

    buffer.writeln('}');
  }

  void _writeGet(StringBuffer buffer, TableNames name, ColumnBinding? keyed) {
    if (keyed != null && !keyed.isNullable) {
      final value =
          keyed.column.kind == ColumnShapeKind.id && keyed.type != 'String'
          ? '${keyed.field}.value'
          : keyed.field;
      buffer
        ..writeln('  /// The single row with this ${keyed.wireKey}.')
        ..writeln('  Future<${name.row}> get(')
        ..writeln('    ${keyed.type} ${keyed.field}, {')
        ..writeln('    List<String> expand = const [],')
        ..writeln('    Authorization? as,')
        ..writeln('  }) =>')
        ..writeln('      _db.get(')
        ..writeln('        body: GetBody(')
        ..writeln('          table: table,')
        ..writeln("          where: Eq('${keyed.wireKey}', $value),")
        ..writeln('          expand: expand,')
        ..writeln('        ),')
        ..writeln('        fromJson: ${name.row}.fromJson,')
        ..writeln('        authorization: as?.header,')
        ..writeln('      );')
        ..writeln();
      return;
    }

    buffer
      ..writeln('  /// The single row matching [where].')
      ..writeln('  Future<${name.row}> get({')
      ..writeln('    required Where where,')
      ..writeln('    List<String> expand = const [],')
      ..writeln('    Authorization? as,')
      ..writeln('  }) =>')
      ..writeln('      _db.get(')
      ..writeln(
        '        body: GetBody(table: table, where: where, '
        'expand: expand),',
      )
      ..writeln('        fromJson: ${name.row}.fromJson,')
      ..writeln('        authorization: as?.header,')
      ..writeln('      );')
      ..writeln();
  }

  void _writeList(
    StringBuffer buffer,
    TableNames name,
    String? expandExample,
  ) {
    buffer
      ..writeln('  /// A page of rows.')
      ..writeln('  ///');
    if (expandExample case final example?) {
      buffer
        ..writeln(
          '  /// `expand` takes the wire paths the server understands --',
        )
        ..writeln('  /// `$example`, dotted and')
        ..writeln('  /// capped at depth 4. Phase 3 replaces them with typed')
        ..writeln('  /// paths; the wire form does not change when it does.');
    } else {
      buffer
        ..writeln('  /// `${name.table}` has no foreign keys, so there is')
        ..writeln('  /// nothing for `expand` to pull in here.');
    }
    buffer
      ..writeln('  Future<Paginated<${name.row}>> list({')
      ..writeln('    Where? where,')
      ..writeln('    int? limit,')
      ..writeln('    int? offset,')
      ..writeln('    List<OrderByTerm>? orderBy,')
      ..writeln('    List<String> expand = const [],')
      ..writeln('    Authorization? as,')
      ..writeln('  }) =>')
      ..writeln('      _db.list(')
      ..writeln('        body: ListBody(')
      ..writeln('          table: table,')
      ..writeln('          where: where,')
      ..writeln('          limit: limit,')
      ..writeln('          offset: offset,')
      ..writeln('          orderBy: orderBy,')
      ..writeln('          expand: expand,')
      ..writeln('        ),')
      ..writeln('        fromJson: ${name.row}.fromJson,')
      ..writeln('        authorization: as?.header,')
      ..writeln('      );')
      ..writeln();
  }

  void _writeCount(StringBuffer buffer, TableNames name) {
    buffer
      ..writeln('  /// How many rows match [where].')
      ..writeln('  Future<int> count({Where? where, Authorization? as}) =>')
      ..writeln('      _db.count(')
      ..writeln('        body: CountBody(table: table, where: where),')
      ..writeln('        authorization: as?.header,')
      ..writeln('      );');
  }

  /// The single primary-key column, or null when there is not exactly one.
  static ColumnShape? _primaryKey(TableSchemaShape shape) {
    final keys = [
      for (final column in shape.columns)
        if (column.isPrimaryKey && !column.isSecret) column,
    ];
    return keys.length == 1 ? keys.first : null;
  }
}
