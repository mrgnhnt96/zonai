/// Phase 1 of the typed client: ids, read models, `ZonaiTables`, and
/// `get` / `list` / `count` with an `Authorization` on every method.
///
/// Deliberately *not* here, and not because they were forgotten: `ColumnRef`
/// tokens, typed `Where` / `OrderByTerm`, the `Patch` family and the write
/// surface (phase 2); `ExpandPath` chaining and `listen` mirrors (phase 3);
/// enum columns as Dart enums and custom operations (phase 4).
///
/// The output is a value, never a write. `--check` has to be able to compare a
/// generation against disk without performing it, which is only possible while
/// the result is still in hand.
final class DartClientEmitter implements ClientEmitter {
  const DartClientEmitter();

  /// The library a consumer imports. Everything else is reachable from here.
  static const barrelFileName = 'zonai_client.g.dart';

  /// Shared runtime: the parse helpers and [Authorization]. One copy, not one
  /// per table.
  static const runtimeFileName = 'zonai_runtime.g.dart';

  @override
  Map<String, String> emit(ClientGenerationInput input) {
    final tables = input.schema.tables;
    final names = ClientNameTable.forTables(tables.keys, input.settings);

    for (final collision in names.collisions) {
      logger.warn(collision.message);
    }

    return {
      barrelFileName: _barrel(input, names),
      runtimeFileName:
          _header(input, about: 'Shared runtime.') + kClientRuntimeSource,
      for (final entry in tables.entries)
        names[entry.key]!.file: _table(input, entry.value, names),
    };
  }

  /// The header every generated file carries.
  ///
  /// §8.3 is in here rather than only in the docs on purpose: a typed API
  /// *reads* as a guarantee, and the file a developer has open is where that
  /// misreading happens.
  ///
  /// `// dart format off` because this output lands in a repo the *consumer*
  /// owns, where `lib/gen` is not excluded from anything. Reformatting it
  /// would put a project's format gate and `zonai gen client --check` in
  /// permanent disagreement: one demands a change the next generation reverts.
  /// The alternative -- formatting the emitted source with `dart_style` here
  /// -- would make the CLI's dart_style version, not the consumer's SDK, decide
  /// what their committed files look like, so version skew becomes churn.
  String _header(ClientGenerationInput input, {required String about}) {
    return '''
$kGeneratedClientHeader
//
// $about
// Generated by `zonai gen client` (zonai ${input.generatorVersion}).
// Schema: ${input.schema.hash}
//
// Types say nothing about permission. `canView` / `canList` / `canUpdate` are
// evaluated on the server and still reject at runtime -- a method existing
// here means the shape is known, not that this caller may call it.

// ignore_for_file: type=lint
// dart format off

''';
  }

  /// The barrel: exports, and the extension that hangs the tables off
  /// `ZonaiClient`.
  String _barrel(ClientGenerationInput input, ClientNameTable names) {
    final tables = input.schema.tables.keys.toList();
    final buffer = StringBuffer(
      _header(input, about: 'The generated typed client.'),
    );

    buffer
      ..writeln("import 'package:zonai_client/zonai_client.dart';")
      ..writeln();
    for (final table in tables) {
      buffer.writeln("import '${names[table]!.file}';");
    }
    buffer
      ..writeln()
      ..writeln(
        "export '$runtimeFileName' show "
        'Authorization, '
        'ColumnRef, '
        'ComparableColumnRef, '
        'ExpandPath, '
        'Field, '
        'ListField, '
        'MapField, '
        'NumField, '
        'Patch, '
        'PhotoId, '
        'zonaiWriteValue, '
        'NullableColumnRef, '
        'StringColumnRef, '
        'ZonaiRowParseException;',
      );
    for (final table in tables) {
      buffer.writeln("export '${names[table]!.file}';");
    }

    buffer
      ..writeln()
      ..writeln('/// The generated tables, hung off the existing client.')
      ..writeln('///')
      ..writeln('/// An extension, never a fork: the dependency arrow points')
      ..writeln('/// generated -> `zonai_client` and never back, so')
      ..writeln('/// `client.posts.list(...)` and')
      ..writeln("/// `client.db.list(body: ListBody(table: 'posts'), ...)` are")
      ..writeln('/// both valid in one file.')
      ..writeln('extension ZonaiTables on ZonaiClient {');

    for (final table in tables) {
      final name = names[table]!;
      final shape = input.schema.tables[table]!;
      buffer
        ..writeln(
          '  /// The `$table` table${shape.isView ? ', a read-only '
                    'view' : ''}.',
        )
        ..writeln('  ${name.api} get ${name.getter} => ${name.api}(db);');
      if (table != tables.last) buffer.writeln();
    }

    buffer.writeln('}');
    return buffer.toString();
  }

  /// One table: its id type, read model, expanded holder and API.
  String _table(
    ClientGenerationInput input,
    TableSchemaShape shape,
    ClientNameTable names,
  ) {
    final table = shape.table;
    final name = names[table]!;
    final columns = [
      for (final column in shape.columns)
        if (ColumnBinding.forColumn(column, table: table, names: names)
            case final binding?)
          binding,
    ];
    final expands = ExpandBinding.forTable(shape, names: names);
    // A view is read-only: the server has nothing to write through.
    final writes = shape.isView
        ? const <WriteBinding>[]
        : WriteBinding.forTable(shape, names: names);
    final secrets = [
      for (final column in shape.columns)
        if (column.isSecret) column.name,
    ];

    final buffer = StringBuffer(
      _header(
        input,
        about: '`$table`${shape.isView ? ' (a read-only view)' : ''}.',
      ),
    );

    buffer.writeln("import 'package:zonai_client/zonai_client.dart';");
    buffer.writeln();
    buffer.writeln("import '../$runtimeFileName';");
    for (final import in _importsFor(shape, names)) {
      buffer.writeln("import '$import';");
    }
    buffer.writeln();

    buffer
      ..writeln("const _r = ZonaiRowReader('$table');")
      ..writeln();

    _writeId(buffer, shape, name);
    _writeRow(buffer, shape, name, columns, expands, secrets);
    if (expands.isNotEmpty) _writeExpanded(buffer, name, expands);
    // Emitted for every table, not only those with expandable keys: a table
    // with none of its own is still the *target* of another table's, and
    // `AuthorsExpand.companyId` has to have a `CompaniesExpand` to return.
    _writeExpand(buffer, name, expands, names);
    _writeTokens(buffer, shape, name, columns, secrets, expands);
    if (writes.isNotEmpty) {
      _writeCreateBuilder(buffer, name, writes);
      _writeUpdateBuilder(buffer, name, writes);
    }
    _writeApi(
      buffer,
      shape,
      name,
      columns,
      _expandExample(expands, input.schema.tables, names, owner: name),
      writes,
    );
    _writeListen(buffer, name, expands);

    return buffer.toString();
  }

  /// The other generated libraries this one names.
  ///
  /// A self-referencing foreign key (`users.manager_id -> users.id`) resolves
  /// to this same file, so it is dropped rather than emitted as an import of
  /// itself.
  List<String> _importsFor(TableSchemaShape shape, ClientNameTable names) {
    final imports = <String>{};
    for (final column in shape.columns) {
      if (column.isSecret) continue;
      if (column.foreignKey case final fk?) {
        if (fk.table == shape.table) continue;
        if (names[fk.table] case final target?) {
          imports.add(target.baseFileName);
        }
      }
    }
    return imports.toList()..sort();
  }

  /// An `expand` example built from THIS table's own foreign keys.
  ///
  /// It used to be the literal `['author_id', 'author_id.company_id']` for
  /// every table in every project -- those are `apps/playground`'s columns, so
  /// the line read as correct there and was wrong everywhere else. It was
  /// printed even on tables with no foreign keys at all, telling a developer
  /// to expand a column their schema does not have.
  ///
  /// Second hop only when the target genuinely has one, because the dotted
  /// form is the whole thing the example exists to teach; a one-element list
  /// demonstrates nothing. Null when the table has no expandable relation --
  /// [_writeList] then says so instead of inventing a column.
  /// Derived from [ExpandBinding.forTable] rather than from the columns
  /// directly, so the example can only ever name a path the generated
  /// `expanded` class actually offers. Reading the foreign keys myself was the
  /// first attempt and it produced `['photo']` for `posts`: `photo` IS a
  /// foreign key, but it points at `_photos`, a skipped system table, so the
  /// generated client cannot expand it. One predicate, in one place.
  String? _expandExample(
    List<ExpandBinding> expands,
    Map<String, TableSchemaShape> tables,
    ClientNameTable names, {
    required TableNames owner,
  }) {
    if (expands.isEmpty) return null;
    final first = expands.first;

    final second = switch (tables[first.targetTable]) {
      final target? =>
        ExpandBinding.forTable(target, names: names)
            // `a.a` teaches the dotted form less clearly than a hop to a
            // different table.
            .where((next) => next.targetTable != first.targetTable)
            .firstOrNull,
      _ => null,
    };

    final root = '${owner.tokens}.expand';
    if (second == null) return '[$root.${first.field}]';
    return '[$root.${first.field}, '
        '$root.${first.field}.${second.field}]';
  }

  void _writeId(StringBuffer buffer, TableSchemaShape shape, TableNames name) {
    final primaryKey = _primaryKey(shape);
    if (primaryKey == null || primaryKey.kind != ColumnShapeKind.id) return;

    buffer
      ..writeln('/// A `${shape.table}` row id.')
      ..writeln('///')
      ..writeln('/// An extension type over `String`, so it erases at runtime:')
      ..writeln(
        '/// it survives `jsonEncode` and `SendPort.send` untouched and',
      )
      ..writeln('/// needs no custom encoder. Passing a different table\'s id')
      ..writeln('/// where this one belongs stops compiling.')
      ..writeln('extension type const ${name.id}(String value) {')
      ..writeln('  /// Parses an id from a raw JSON value.')
      ..writeln('  static ${name.id} fromJson(Object? json) => switch (json) {')
      ..writeln('        final String value => ${name.id}(value),')
      ..writeln('        _ => throw ZonaiRowParseException(')
      ..writeln("            table: '${shape.table}',")
      ..writeln("            column: '${primaryKey.name}',")
      ..writeln("            expected: 'id (String)',")
      ..writeln('            actual: json.runtimeType,')
      ..writeln('          ),')
      ..writeln('      };')
      ..writeln()
      ..writeln('  String toJson() => value;')
      ..writeln('}')
      ..writeln();
  }

  void _writeRow(
    StringBuffer buffer,
    TableSchemaShape shape,
    TableNames name,
    List<ColumnBinding> columns,
    List<ExpandBinding> expands,
    List<String> secrets,
  ) {
    buffer
      ..writeln('/// One `${shape.table}` row, decoded.')
      ..writeln('///');
    if (secrets.isNotEmpty) {
      buffer
        ..writeln(
          '/// ${secrets.map((s) => '`$s`').join(', ')} '
          '${secrets.length == 1 ? 'is a secret column and is' : 'are secret '
                    'columns and are'} stripped from every',
        )
        ..writeln(
          '/// response, so ${secrets.length == 1 ? 'it has' : 'they '
                    'have'} no field here -- absent rather than',
        )
        ..writeln('/// nullable-and-always-null.')
        ..writeln('///');
    }
    buffer
      ..writeln('/// Values arrive as raw SQLite storage and are decoded here:')
      ..writeln('/// epoch milliseconds become `DateTime`, `0`/`1` becomes')
      ..writeln('/// `bool`, JSON-encoded text becomes a list or a map.')
      ..writeln('final class ${name.row} {')
      ..writeln('  const ${name.row}({');

    for (final column in columns) {
      buffer.writeln(
        '    ${column.isNullable ? '' : 'required '}this.${column.field},',
      );
    }
    if (expands.isNotEmpty) buffer.writeln('    this.expanded,');
    buffer
      ..writeln('  });')
      ..writeln();

    for (final column in columns) {
      buffer.writeln(
        '  /// `${column.wireKey}` -- ${column.column.kind.toJson()}.',
      );
      buffer.writeln('  final ${column.type} ${column.field};');
      buffer.writeln();
    }
    if (expands.isNotEmpty) {
      buffer
        ..writeln('  /// Related rows, when the call asked for them. Null')
        ..writeln('  /// otherwise -- an unexpanded row is not an error.')
        ..writeln('  final ${name.expanded}? expanded;')
        ..writeln();
    }

    buffer.writeln(
      '  factory ${name.row}.fromJson(Map<String, Object?> json) => '
      '${name.row}(',
    );
    for (final column in columns) {
      buffer.writeln('        ${column.field}: ${column.parseExpression},');
    }
    if (expands.isNotEmpty) {
      buffer.writeln(
        "        expanded: ${name.expanded}.tryFromJson(json['expanded']),",
      );
    }
    buffer
      ..writeln('      );')
      ..writeln('}')
      ..writeln();
  }

  void _writeExpanded(
    StringBuffer buffer,
    TableNames name,
    List<ExpandBinding> expands,
  ) {
    buffer
      ..writeln('/// The rows related to a `${name.table}` row.')
      ..writeln('///')
      ..writeln(
        '/// One field per expandable foreign key, keyed on the wire by',
      )
      ..writeln('/// the foreign-key column name. Each related row carries its')
      ..writeln('/// own `expanded`, so depth is recursion rather than a new')
      ..writeln('/// type.')
      ..writeln('final class ${name.expanded} {')
      ..writeln('  const ${name.expanded}({');
    for (final expand in expands) {
      buffer.writeln('    this.${expand.field},');
    }
    buffer
      ..writeln('  });')
      ..writeln();

    for (final expand in expands) {
      buffer
        ..writeln(
          '  /// The `${expand.targetTable}` row `${expand.wireKey}` '
          'points at.',
        )
        ..writeln('  final ${expand.rowType}? ${expand.field};')
        ..writeln();
    }

    buffer.writeln(
      '  factory ${name.expanded}.fromJson(Map<String, Object?> json) => '
      '${name.expanded}(',
    );
    for (final expand in expands) {
      buffer.writeln(
        '        ${expand.field}: switch '
        "(ZonaiRowReader.nested(json['${expand.wireKey}'])) {",
      );
      buffer
        ..writeln('          final row? => ${expand.rowType}.fromJson(row),')
        ..writeln('          _ => null,')
        ..writeln('        },');
    }
    buffer
      ..writeln('      );')
      ..writeln()
      ..writeln('  /// Null when the response carried no `expanded` object.')
      ..writeln(
        '  static ${name.expanded}? tryFromJson(Object? json) => '
        'switch (ZonaiRowReader.nested(json)) {',
      )
      ..writeln('        final map? => ${name.expanded}.fromJson(map),')
      ..writeln('        _ => null,')
      ..writeln('      };')
      ..writeln('}')
      ..writeln();
  }

  /// The column-token holder: one `ColumnRef` per column the client can see.
  ///
  /// This is the whole of §5.4. Every token carries the column's Dart type, so
  /// the operator set a call site can reach is decided by the schema rather
  /// than by the author remembering: `contains` exists on a text column and
  /// nowhere else, `isNull` on a nullable column and nowhere else.
  ///
  /// Secret columns are already absent from [columns] -- `ColumnBinding`
  /// returns null for them -- so no token can be minted for one, and the
  /// server's `SecretColumnFilterException` becomes unreachable from here.
  void _writeTokens(
    StringBuffer buffer,
    TableSchemaShape shape,
    TableNames name,
    List<ColumnBinding> columns,
    List<String> secrets,
    List<ExpandBinding> expands,
  ) {
    buffer
      ..writeln('/// Typed column tokens for `${shape.table}`.')
      ..writeln('///')
      ..writeln(
        '/// Each token builds a plain `Where` or `OrderByTerm`, so the',
      )
      ..writeln('/// wire form is exactly what the untyped client sends.')
      ..writeln('///')
      ..writeln('/// Columns whose stored value differs from their decoded')
      ..writeln('/// Dart value get no token -- a photo (stores an id, reads')
      ..writeln('/// back a URL), and the JSON-encoded kinds (`list`, `map`,')
      ..writeln('/// `enumList`, blob) plus `bigInt`. A filter built from the')
      ..writeln('/// decoded value would match nothing or throw, and a token')
      ..writeln('/// that cannot work is worse than no token at all.');
    if (secrets.isNotEmpty) {
      buffer
        ..writeln('///')
        ..writeln('/// No token is emitted for ${_englishList(secrets)} --')
        ..writeln('/// a secret column is stripped from every response and')
        ..writeln('/// rejected in a filter, so it cannot be named here.');
    }
    buffer
      ..writeln('abstract final class ${name.tokens} {')
      ..writeln('  /// The wire name of this table.')
      ..writeln("  static const table = '${shape.table}';");

    buffer
      ..writeln()
      ..writeln('  /// The root of a typed `expand` path.')
      ..writeln('  static const expand = ${name.expand}([]);');

    for (final binding in columns) {
      // Not every column can carry an honest token -- see
      // `ColumnBinding.isTokenable` for the seven kinds that cannot and the
      // measurement behind each.
      if (!ColumnBinding.isTokenable(binding.column.kind)) continue;

      final ref = binding.isNullable ? 'NullableColumnRef' : 'ColumnRef';
      buffer
        ..writeln()
        ..writeln('  /// The `${binding.wireKey}` column.')
        ..writeln(
          '  static const ${binding.field} = '
          '$ref<${_nonNullable(binding.type)}>'
          "('${binding.wireKey}');",
        );
    }

    buffer
      ..writeln('}')
      ..writeln();
  }

  /// The typed `expand` path builder for this table.
  ///
  /// One getter per expandable foreign key, each returning the *referenced*
  /// table's builder -- so `Posts.expand.authorId.companyId` type-checks the
  /// whole way down and `Posts.expand.authorId.title` does not exist. The
  /// graph comes from [ExpandBinding.forTable], which already excludes a photo
  /// column's foreign key into the framework-internal `_photos`.
  ///
  /// A self-referencing key (`users.manager_id -> users.id`) yields a getter
  /// returning this same type, chainable to any depth -- which is exactly why
  /// the depth cap on `ExpandPath` is an assert and not a type.
  void _writeExpand(
    StringBuffer buffer,
    TableNames name,
    List<ExpandBinding> expands,
    ClientNameTable names,
  ) {
    buffer
      ..writeln('/// Typed `expand` paths rooted at a `${name.table}` row.')
      ..writeln('///')
      ..writeln('/// Reach one through `${name.tokens}.expand`. Each hop is')
      ..writeln('/// typed by the table it points at, and the value sent is')
      ..writeln('/// the same dotted string the untyped client takes.')
      ..writeln('final class ${name.expand} extends ExpandPath {')
      ..writeln('  const ${name.expand}(super.segments);');

    if (expands.isEmpty) {
      buffer
        ..writeln()
        ..writeln('  // No expandable foreign keys on this table. The type')
        ..writeln('  // still exists because another table may point here.');
    }

    for (final expand in expands) {
      final target = names[expand.targetTable]!;
      buffer
        ..writeln()
        ..writeln(
          '  /// Expand the `${expand.targetTable}` row '
          '`${expand.wireKey}` points at.',
        )
        ..writeln(
          '  ${target.expand} get ${expand.field} => '
          "${target.expand}([...segments, '${expand.wireKey}']);",
        );
    }

    buffer
      ..writeln('}')
      ..writeln();
  }

  /// The create builder: a plain value per column, no `Patch`.
  ///
  /// There is no absent/NULL ambiguity on insert -- omitting a nullable column
  /// and inserting NULL into it are the same thing -- so create stays plain and
  /// only update pays the `Field.set(...)` cost.
  void _writeCreateBuilder(
    StringBuffer buffer,
    TableNames name,
    List<WriteBinding> writes,
  ) {
    buffer
      ..writeln('/// The columns a new `${name.table}` row may set.')
      ..writeln('///')
      ..writeln('/// Read-only columns are absent: `created_at`, `updated_at`')
      ..writeln('/// and anything the server generates. A secret column IS')
      ..writeln('/// here -- it is stripped from responses, not from writes.')
      ..writeln('final class ${name.create} {')
      ..writeln('  const ${name.create}({');
    for (final write in writes) {
      final req = write.isRequiredOnCreate ? 'required ' : '';
      buffer.writeln('    ${req}this.${write.field},');
    }
    buffer
      ..writeln('  });')
      ..writeln();

    for (final write in writes) {
      final opt = write.isRequiredOnCreate ? '' : '?';
      buffer
        ..writeln('  /// The `${write.wireKey}` column.')
        ..writeln('  final ${write.type}$opt ${write.field};')
        ..writeln();
    }

    buffer
      ..writeln('  /// The wire object, omitting every column not supplied.')
      ..writeln('  Map<String, dynamic> toObject() => {');
    for (final write in writes) {
      final expression = _writeValueExpression(write);
      if (write.isRequiredOnCreate) {
        buffer.writeln("        '${write.wireKey}': $expression,");
      } else {
        buffer.writeln(
          '        if (${write.field} != null) '
          "'${write.wireKey}': $expression,",
        );
      }
    }
    buffer
      ..writeln('      };')
      ..writeln('}')
      ..writeln();
  }

  /// The update builder: one `Patch` per column, so NULL is expressible.
  void _writeUpdateBuilder(
    StringBuffer buffer,
    TableNames name,
    List<WriteBinding> writes,
  ) {
    buffer
      ..writeln('/// The changes to apply to matching `${name.table}` rows.')
      ..writeln('///')
      ..writeln('/// Each field takes a `Patch` rather than a raw value, which')
      ..writeln('/// is what makes "leave alone" and "set to NULL" different')
      ..writeln('/// call sites instead of the same `null`.')
      ..writeln('final class ${name.update} {')
      ..writeln('  const ${name.update}({');
    for (final write in writes) {
      buffer.writeln('    this.${write.field},');
    }
    buffer
      ..writeln('  });')
      ..writeln();

    for (final write in writes) {
      buffer
        ..writeln('  /// The `${write.wireKey}` column.')
        ..writeln('  final ${write.patch}<${write.patchType}>? ${write.field};')
        ..writeln();
    }

    buffer
      ..writeln('  /// One `ColumnUpdate` per field actually supplied.')
      ..writeln('  List<Update> toUpdates() => [');
    for (final write in writes) {
      buffer.writeln(
        '        if (${write.field} case final p?) '
        "ColumnUpdate('${write.wireKey}', p.value),",
      );
    }
    buffer
      ..writeln('      ];')
      ..writeln('}')
      ..writeln();
  }

  /// How a create field reaches the wire.
  ///
  /// An extension-type id erases to its `String` at runtime, but `toObject`
  /// declares `Map<String, dynamic>` and the value is jsonEncoded downstream --
  /// `.value` makes the unwrapping explicit rather than relying on erasure.
  String _writeValueExpression(WriteBinding write) {
    final field = write.field;
    final bang = write.isRequiredOnCreate ? '' : '!';
    final unwrapped = switch (write.column.kind) {
      ColumnShapeKind.photo => '$field$bang.value',
      ColumnShapeKind.photos => '[for (final p in $field$bang) p.value]',
      ColumnShapeKind.id when write.type != 'String' => '$field$bang.value',
      _ => field + bang,
    };

    // Everything goes through the same normalizer the `Patch` constructors
    // use, so create and update cannot disagree about an encoding. It is a
    // no-op on a `String` or an `int`; on a `DateTime` it is the difference
    // between a request and a `JsonUnsupportedObjectError`.
    return 'zonaiWriteValue($unwrapped)';
  }

  /// `DateTime?` -> `DateTime`. A token's type parameter is always the
  /// non-nullable one; see `ColumnRef`'s own doc for why.
  static String _nonNullable(String type) =>
      type.endsWith('?') ? type.substring(0, type.length - 1) : type;

  /// `[a]` -> '`a`'; `[a, b]` -> '`a` and `b`'; `[a, b, c]` -> '`a`, `b` and `c`'.
  static String _englishList(List<String> items) {
    final quoted = [for (final item in items) '`$item`'];
    if (quoted.length == 1) return quoted.single;
    return '${quoted.sublist(0, quoted.length - 1).join(', ')} '
        'and ${quoted.last}';
  }

  void _writeApi(
    StringBuffer buffer,
    TableSchemaShape shape,
    TableNames name,
    List<ColumnBinding> columns,
    String? expandExample,
    List<WriteBinding> writes,
  ) {
    final primaryKey = _primaryKey(shape);
    final keyed = primaryKey == null
        ? null
        : columns
              .where((binding) => binding.column.name == primaryKey.name)
              .firstOrNull;

    buffer
      ..writeln('/// Reads of the `${shape.table}` table.')
      ..writeln('///');
    if (shape.isView) {
      buffer
        ..writeln('/// A read-only view: it has no `sqlite_master` row and no')
        ..writeln('/// write operations, so there is nothing else to offer.')
        ..writeln('///');
    }
    buffer
      ..writeln('/// Every method takes an optional `as` and falls through to')
      ..writeln('/// the client\'s ambient token when it is omitted.')
      ..writeln('final class ${name.api} {')
      ..writeln('  const ${name.api}(this._db);')
      ..writeln()
      ..writeln('  /// The wire name of this table.')
      ..writeln("  static const table = '${shape.table}';")
      ..writeln()
      ..writeln('  final Db _db;')
      ..writeln();

    _writeGet(buffer, name, keyed);
    _writeList(buffer, name, expandExample);
    _writeCount(buffer, name);
    if (writes.isNotEmpty) _writeMutations(buffer, name);
    buffer
      ..writeln()
      ..writeln('  /// The live-query mirror of `get` / `list` / `count`.')
      ..writeln('  ${name.listen} get listen => ${name.listen}(_db);');

    buffer.writeln('}');
  }

  void _writeGet(StringBuffer buffer, TableNames name, ColumnBinding? keyed) {
    if (keyed != null && !keyed.isNullable) {
      final value =
          keyed.column.kind == ColumnShapeKind.id && keyed.type != 'String'
          ? '${keyed.field}.value'
          : keyed.field;
      buffer
        ..writeln('  /// The single row with this ${keyed.wireKey}.')
        ..writeln('  Future<${name.row}> get(')
        ..writeln('    ${keyed.type} ${keyed.field}, {')
        ..writeln('    List<ExpandPath> expand = const [],')
        ..writeln('    Authorization? as,')
        ..writeln('  }) =>')
        ..writeln('      _db.get(')
        ..writeln('        body: GetBody(')
        ..writeln('          table: table,')
        ..writeln("          where: Eq('${keyed.wireKey}', $value),")
        ..writeln('          expand: [for (final e in expand) e.path],')
        ..writeln('        ),')
        ..writeln('        fromJson: ${name.row}.fromJson,')
        ..writeln('        authorization: as?.header,')
        ..writeln('      );')
        ..writeln();
      return;
    }

    buffer
      ..writeln('  /// The single row matching [where].')
      ..writeln('  Future<${name.row}> get({')
      ..writeln('    required Where where,')
      ..writeln('    List<ExpandPath> expand = const [],')
      ..writeln('    Authorization? as,')
      ..writeln('  }) =>')
      ..writeln('      _db.get(')
      ..writeln(
        '        body: GetBody(table: table, where: where, '
        'expand: [for (final e in expand) e.path]),',
      )
      ..writeln('        fromJson: ${name.row}.fromJson,')
      ..writeln('        authorization: as?.header,')
      ..writeln('      );')
      ..writeln();
  }

  void _writeList(StringBuffer buffer, TableNames name, String? expandExample) {
    buffer
      ..writeln('  /// A page of rows.')
      ..writeln('  ///')
      ..writeln('  /// `groupBy` takes a single column token. The server does')
      ..writeln('  /// not add aggregates, so rows come back in the ordinary')
      ..writeln('  /// row shape and `${name.row}.fromJson` still applies.')
      ..writeln('  ///');
    if (expandExample case final example?) {
      buffer
        ..writeln('  /// `expand` takes typed paths -- `$example`.')
        ..writeln('  /// The server caps depth at 4 and keys each expanded')
        ..writeln('  /// row by its foreign-key column name.');
    } else {
      buffer
        ..writeln('  /// `${name.table}` has no foreign keys, so there is')
        ..writeln('  /// nothing for `expand` to pull in here.');
    }
    buffer
      ..writeln('  Future<Paginated<${name.row}>> list({')
      ..writeln('    Where? where,')
      ..writeln('    int? limit,')
      ..writeln('    int? offset,')
      ..writeln('    List<OrderByTerm>? orderBy,')
      ..writeln('    ColumnRef<Object?>? groupBy,')
      ..writeln('    List<ExpandPath> expand = const [],')
      ..writeln('    Authorization? as,')
      ..writeln('  }) =>')
      ..writeln('      _db.list(')
      ..writeln('        body: ListBody(')
      ..writeln('          table: table,')
      ..writeln('          where: where,')
      ..writeln('          limit: limit,')
      ..writeln('          offset: offset,')
      ..writeln('          orderBy: orderBy,')
      ..writeln('          groupBy: groupBy?.name,')
      ..writeln('          expand: [for (final e in expand) e.path],')
      ..writeln('        ),')
      ..writeln('        fromJson: ${name.row}.fromJson,')
      ..writeln('        authorization: as?.header,')
      ..writeln('      );')
      ..writeln();
  }

  void _writeCount(StringBuffer buffer, TableNames name) {
    buffer
      ..writeln('  /// How many rows match [where].')
      ..writeln('  Future<int> count({Where? where, Authorization? as}) =>')
      ..writeln('      _db.count(')
      ..writeln('        body: CountBody(table: table, where: where),')
      ..writeln('        authorization: as?.header,')
      ..writeln('      );');
  }

  /// `create` / `createMany` / `update` / `updateMany` / `delete` /
  /// `deleteMany` -- the six `Db` operations that had no typed mirror.
  ///
  /// Emitted only for a real table. A view has no write surface because the
  /// server has nothing to write through.
  void _writeMutations(StringBuffer buffer, TableNames name) {
    buffer
      ..writeln()
      ..writeln('  /// Inserts one row and returns it as the server stored it.')
      ..writeln('  Future<${name.row}> create(')
      ..writeln('    ${name.create} object, {')
      ..writeln('    Authorization? as,')
      ..writeln('  }) =>')
      ..writeln('      _db.create(')
      ..writeln(
        '        body: CreateBody(table: table, object: object.toObject()),',
      )
      ..writeln('        fromJson: ${name.row}.fromJson,')
      ..writeln('        authorization: as?.header,')
      ..writeln('      );')
      ..writeln()
      ..writeln('  /// Inserts many rows in one request.')
      ..writeln('  Future<List<${name.row}>> createMany(')
      ..writeln('    List<${name.create}> objects, {')
      ..writeln('    Authorization? as,')
      ..writeln('  }) =>')
      ..writeln('      _db.createMany(')
      ..writeln('        body: CreateManyBody(')
      ..writeln('          table: table,')
      ..writeln('          objects: [for (final o in objects) o.toObject()],')
      ..writeln('        ),')
      ..writeln('        fromJson: ${name.row}.fromJson,')
      ..writeln('        authorization: as?.header,')
      ..writeln('      );')
      ..writeln()
      ..writeln('  /// Applies [set] to the single row matching [where].')
      ..writeln('  Future<${name.row}> update({')
      ..writeln('    required Where where,')
      ..writeln('    required ${name.update} set,')
      ..writeln('    Authorization? as,')
      ..writeln('  }) =>')
      ..writeln('      _db.update(')
      ..writeln('        body: UpdateOneBody(')
      ..writeln('          table: table,')
      ..writeln('          where: where,')
      ..writeln('          updates: set.toUpdates(),')
      ..writeln('        ),')
      ..writeln('        fromJson: ${name.row}.fromJson,')
      ..writeln('        authorization: as?.header,')
      ..writeln('      );')
      ..writeln()
      ..writeln('  /// Applies [set] to every row matching [where].')
      ..writeln('  Future<List<${name.row}>> updateMany({')
      ..writeln('    required Where where,')
      ..writeln('    required ${name.update} set,')
      ..writeln('    int? limit,')
      ..writeln('    Authorization? as,')
      ..writeln('  }) =>')
      ..writeln('      _db.updateMany(')
      ..writeln('        body: UpdateBody(')
      ..writeln('          table: table,')
      ..writeln('          where: where,')
      ..writeln('          limit: limit,')
      ..writeln('          updates: set.toUpdates(),')
      ..writeln('        ),')
      ..writeln('        fromJson: ${name.row}.fromJson,')
      ..writeln('        authorization: as?.header,')
      ..writeln('      );')
      ..writeln()
      ..writeln('  /// Deletes the single row matching [where].')
      ..writeln('  Future<void> delete({')
      ..writeln('    required Where where,')
      ..writeln('    Authorization? as,')
      ..writeln('  }) =>')
      ..writeln('      _db.delete(')
      ..writeln('        body: DeleteOneBody(table: table, where: where),')
      ..writeln('        authorization: as?.header,')
      ..writeln('      );')
      ..writeln()
      ..writeln('  /// Deletes every row matching [where].')
      ..writeln('  Future<void> deleteMany({')
      ..writeln('    required Where where,')
      ..writeln('    int? limit,')
      ..writeln('    Authorization? as,')
      ..writeln('  }) =>')
      ..writeln('      _db.deleteMany(')
      ..writeln(
        '        body: DeleteBody(table: table, where: where, limit: limit),',
      )
      ..writeln('        authorization: as?.header,')
      ..writeln('      );');
  }

  /// `listen.one` / `listen.list` / `listen.count` -- the typed mirror of
  /// `DbListen`.
  ///
  /// `list` returns `Stream<List<Row>>` and NOT `Stream<Paginated<Row>>`,
  /// because that is what `DbListen.list` actually returns. Mirroring the
  /// non-streaming shape here would be a nicer symmetry and a lie.
  ///
  /// `where` is required on `one` and `count` because `StreamBody` and
  /// `StreamCountBody` require it; it is optional on `list`, where
  /// `StreamListBody` makes it so.
  void _writeListen(
    StringBuffer buffer,
    TableNames name,
    List<ExpandBinding> expands,
  ) {
    buffer
      ..writeln('/// Live queries over `${name.table}`.')
      ..writeln('///')
      ..writeln('/// Reach one through `client.${name.getter}.listen`. Each')
      ..writeln('/// stream is the same subscription `client.db.listen`')
      ..writeln('/// opens -- this only types the rows coming out of it.')
      ..writeln('final class ${name.listen} {')
      ..writeln('  const ${name.listen}(this._db);')
      ..writeln()
      ..writeln('  /// The wire name of this table.')
      ..writeln("  static const table = '${name.table}';")
      ..writeln()
      ..writeln('  final Db _db;')
      ..writeln()
      ..writeln('  /// The single row matching [where], re-emitted on change.')
      ..writeln('  Stream<${name.row}> one({')
      ..writeln('    required Where where,')
      ..writeln('    List<ExpandPath> expand = const [],')
      ..writeln('    Authorization? as,')
      ..writeln('  }) =>')
      ..writeln('      _db.listen.one(')
      ..writeln('        body: StreamBody(')
      ..writeln('          table: table,')
      ..writeln('          where: where,')
      ..writeln('          expand: [for (final e in expand) e.path],')
      ..writeln('        ),')
      ..writeln('        fromJson: ${name.row}.fromJson,')
      ..writeln('        authorization: as?.header,')
      ..writeln('      );')
      ..writeln()
      ..writeln('  /// Every matching row, re-emitted on change.')
      ..writeln('  ///')
      ..writeln('  /// A plain `List`, not a `Paginated` -- the streaming')
      ..writeln('  /// endpoint carries no page metadata.')
      ..writeln('  Stream<List<${name.row}>> list({')
      ..writeln('    Where? where,')
      ..writeln('    int? limit,')
      ..writeln('    int? offset,')
      ..writeln('    List<OrderByTerm>? orderBy,')
      ..writeln('    ColumnRef<Object?>? groupBy,')
      ..writeln('    List<ExpandPath> expand = const [],')
      ..writeln('    Authorization? as,')
      ..writeln('  }) =>')
      ..writeln('      _db.listen.list(')
      ..writeln('        body: StreamListBody(')
      ..writeln('          table: table,')
      ..writeln('          where: where,')
      ..writeln('          limit: limit,')
      ..writeln('          offset: offset,')
      ..writeln('          orderBy: orderBy,')
      ..writeln('          groupBy: groupBy?.name,')
      ..writeln('          expand: [for (final e in expand) e.path],')
      ..writeln('        ),')
      ..writeln('        fromJson: ${name.row}.fromJson,')
      ..writeln('        authorization: as?.header,')
      ..writeln('      );')
      ..writeln()
      ..writeln('  /// How many rows match [where], re-emitted on change.')
      ..writeln('  Stream<int> count({')
      ..writeln('    required Where where,')
      ..writeln('    Authorization? as,')
      ..writeln('  }) =>')
      ..writeln('      _db.listen.count(')
      ..writeln('        body: StreamCountBody(table: table, where: where),')
      ..writeln('        authorization: as?.header,')
      ..writeln('      );')
      ..writeln('}')
      ..writeln();
  }

  /// The single primary-key column, or null when there is not exactly one.
  static ColumnShape? _primaryKey(TableSchemaShape shape) {
    final keys = [
      for (final column in shape.columns)
        if (column.isPrimaryKey && !column.isSecret) column,
    ];
    return keys.length == 1 ? keys.first : null;
  }
